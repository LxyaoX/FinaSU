package me.weishu.kernelsu.data.rekernelx

import com.topjohnwu.superuser.Shell
import com.topjohnwu.superuser.ShellUtils
import java.io.File
import me.weishu.kernelsu.data.model.RekernelXStatus
import me.weishu.kernelsu.ksuApp
import me.weishu.kernelsu.ui.util.execKsudResult

/**
 * Stages and loads the ReKernel-X driver FinaSU ships in `assets/rekernel_x`.
 *
 * The upstream project normally ships the same `.ko` files inside a flashable module whose
 * `post-fs-data.sh` insmods them. Bundling the files lets the manager do that itself:
 *
 * 1. pick the build that matches the running KMI and copy it to `/data/adb/rekernel_x`;
 * 2. record that file name in `/data/adb/rekernel_x/driver`, so the boot script loads exactly the
 *    build this manager staged instead of guessing from a directory that may hold older copies;
 * 3. drop `/data/adb/post-fs-data.d/neosu_rekernel_x.sh`, which ksud runs before zygote;
 * 4. load it immediately through `ksud insmod` so the toggle needs no reboot.
 *
 * Disabling only removes the boot script: unloading an LKM that hooks binder and netfilter live can
 * take the device down, so the loaded driver stays until the next reboot.
 */
object RekernelXInstaller {
    /** Version of the bundled driver; keep in sync with the file names in the assets. */
    const val VERSION = "1.6"

    private const val ASSET_DIR = "rekernel_x"
    private const val ASSET_PREFIX = "rekernel_x-"
    private const val TARGET_DIR = "/data/adb/rekernel_x"
    private const val BOOT_SCRIPT = "/data/adb/post-fs-data.d/neosu_rekernel_x.sh"
    private const val MODULE_DIR = "/data/adb/modules/rekernel_x"

    /**
     * Name of the staged driver.
     *
     * The summary, the probe and the boot script all resolve the same fact from here, so what the
     * page names is what the kernel is asked to load.
     */
    private const val DRIVER_STATE = "/data/adb/rekernel_x/driver"

    /** Why the last hot load failed, so a rejected `insmod` does not look like a reboot problem. */
    private const val LOAD_LOG = "/data/adb/rekernel_x/last_load"

    /** Long enough to name the failing symbol, short enough to stay one line in the summary. */
    private const val MAX_REASON_CHARS = 120

    /**
     * Resolves the driver to load into `$driver`.
     *
     * The recorded name wins; the newest file is only a fallback for a directory an older build
     * populated. The probe and the boot script share this text because they run in different
     * places, and a mismatch between them is exactly what made the page name a build that the
     * kernel never loaded.
     */
    private const val DRIVER_RESOLVE =
        "driver=\"\"; " +
            "[ -f '$DRIVER_STATE' ] && driver=\$(cat '$DRIVER_STATE' 2>/dev/null); " +
            "[ -n \"\$driver\" ] && [ -f \"$TARGET_DIR/\$driver\" ] || " +
            "driver=\$(ls -1t $TARGET_DIR/rekernel_x-*.ko 2>/dev/null | head -n 1 | sed 's|.*/||')"

    private val probeScript = """
if [ -d /sys/module/rekernel_x ]; then echo rkx:loaded=1; else echo rkx:loaded=0; fi
if [ -e $BOOT_SCRIPT ]; then echo rkx:autoload=1; else echo rkx:autoload=0; fi
# A module the user disabled still owns the directory but loads nothing, so the bundled driver
# has to stay usable.
if [ -d $MODULE_DIR ] && [ ! -e $MODULE_DIR/disable ]; then echo rkx:module=1; else echo rkx:module=0; fi
uname -r | sed 's/^/rkx:release=/'
$DRIVER_RESOLVE
[ -n "${'$'}driver" ] && echo "rkx:driver=${'$'}driver"
if [ -s $LOAD_LOG ]; then echo "rkx:lasterror=${'$'}(head -n 1 $LOAD_LOG)"; fi
""".trimIndent()

    /**
     * What ksud runs at post-fs-data. Plain `insmod` mirrors the upstream module; `ksud insmod`
     * is preferred because it resolves kernel symbols, so it also covers builds whose CRCs do
     * not match byte for byte. Removing this file is the whole "off" state.
     */
    private val bootScriptContent = """
#!/system/bin/sh
# Generated by FinaSU: loads the bundled ReKernel-X driver before zygote starts.
# Delete this file (or turn the switch off in FinaSU) to stop loading it.
[ -d /sys/module/rekernel_x ] && exit 0
$DRIVER_RESOLVE
[ -n "${'$'}driver" ] || exit 0
ko="$TARGET_DIR/${'$'}driver"
[ -f "${'$'}ko" ] || exit 0
if [ -x /data/adb/ksud ]; then
  /data/adb/ksud insmod "${'$'}ko" && exit 0
fi
insmod "${'$'}ko"
""".trimIndent()

    /** Driver file names shipped in the APK, newest first, so a KMI with two builds picks the new one. */
    fun bundledDrivers(): List<String> = runCatching {
        ksuApp.assets.list(ASSET_DIR)
            ?.filter { it.startsWith(ASSET_PREFIX) && it.endsWith(".ko") }
            ?.sortedDescending()
            ?: emptyList()
    }.getOrDefault(emptyList())

    /** The bundled driver for [kmi], empty when this kernel has no build. */
    fun driverFor(kmi: String): String {
        if (kmi.isEmpty()) return ""
        return bundledDrivers().firstOrNull { it.startsWith("$ASSET_PREFIX$kmi-") }.orEmpty()
    }

    fun status(): RekernelXStatus {
        val stdout = ArrayList<String>()
        Shell.getShell().newJob().add(probeScript).to(stdout).exec()
        val probe = RekernelXStatus.fromProbe(stdout.joinToString("\n"))
        return probe.copy(bundledDriver = driverFor(probe.kmi))
    }

    /** Stages [status]'s driver and arms the boot script; returns the staged file name. */
    suspend fun enable(status: RekernelXStatus): String {
        require(!status.externalModule) {
            "a flashed ReKernel-X module already loads the driver"
        }
        val driver = status.bundledDriver
        require(driver.isNotEmpty()) { "no bundled driver for ${status.kernelRelease}" }

        val cached = File(ksuApp.cacheDir, driver)
        ksuApp.assets.open("$ASSET_DIR/$driver").use { input ->
            cached.outputStream().use { output -> input.copyTo(output) }
        }
        val staged = "$TARGET_DIR/$driver"
        check(
            ShellUtils.fastCmdResult(
                "mkdir -p $TARGET_DIR /data/adb/post-fs-data.d && " +
                    // A build an older version staged has to go: the fallback picks the newest file,
                    // so a stale copy with a later timestamp would beat the one just staged.
                    "rm -f $TARGET_DIR/rekernel_x-*.ko && " +
                    "cp '${cached.absolutePath}' '$staged' && " +
                    "chmod 0644 '$staged' && chown 0:0 '$staged' && " +
                    "echo '$driver' > '$DRIVER_STATE.tmp' && " +
                    "chmod 0644 '$DRIVER_STATE.tmp' && " +
                    "mv -f '$DRIVER_STATE.tmp' '$DRIVER_STATE'"
            )
        ) { "could not stage $driver" }

        val script = File(ksuApp.cacheDir, "neosu_rekernel_x.sh")
        script.writeText(bootScriptContent)
        check(
            ShellUtils.fastCmdResult(
                "cp '${script.absolutePath}' '$BOOT_SCRIPT' && " +
                    "chmod 0755 '$BOOT_SCRIPT' && chown 0:0 '$BOOT_SCRIPT'"
            )
        ) { "could not write $BOOT_SCRIPT" }

        // A rejected load is the difference between "running now" and "running after a reboot",
        // and the reason would otherwise only be in dmesg, so keep it where the page can show it.
        if (!status.loaded) {
            val result = execKsudResult("insmod '$staged'")
            recordLoad(if (result.isSuccess) "" else insmodFailure(result))
        }
        return driver
    }

    fun disable() {
        check(ShellUtils.fastCmdResult("rm -f '$BOOT_SCRIPT'")) {
            "could not remove $BOOT_SCRIPT"
        }
    }

    /** Keeps one line of the last load attempt; an empty [message] means it succeeded. */
    private fun recordLoad(message: String) {
        if (message.isEmpty()) {
            ShellUtils.fastCmdResult("rm -f '$LOAD_LOG'")
            return
        }
        val file = File(ksuApp.cacheDir, "rekernel_x_last_load")
        file.writeText(message)
        ShellUtils.fastCmdResult("cp '${file.absolutePath}' '$LOAD_LOG' && chmod 0644 '$LOAD_LOG'")
    }

    /** `insmod` reports on stderr; fall back to the exit code when it said nothing. */
    private fun insmodFailure(result: Shell.Result): String {
        val reason = (result.err + result.out)
            .asSequence()
            .map { it.trim() }
            .firstOrNull { it.isNotEmpty() }
        // One line, bounded: this ends up in a settings row, not in a log viewer.
        return reason?.let { "insmod: ${it.take(MAX_REASON_CHARS)}" }
            ?: "insmod failed (exit ${result.code})"
    }
}
